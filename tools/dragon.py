#!/usr/bin/env python3
"""Deep Dragon frames: assets/creatures/deep-dragon.png (a strip of 56 x 56 frames, transparent background)
-> firmware/src/sprites_dragon.h, one shared palette with three colourways (the three bass eggs).
   python3 tools/dragon.py"""
import colorsys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
S = 56
FRAMES = ["IDLE0", "BLINK", "IDLE1", "IDLE2", "HAPPY0", "HAPPY1", "DANCE0", "DANCE1", "DANCE2", "SLEEP"]
HUES = [0.0, -0.22, 0.30]          # green (the art as drawn), ember, frost

im = Image.open(ROOT / "assets/creatures/deep-dragon.png").convert("RGBA")
pal, frames = [], []
for k in range(len(FRAMES)):
    px = []
    for y in range(S):
        for x in range(S):
            r, g, b, a = im.getpixel((k * S + x, y))
            if a < 128:
                px.append(0)
                continue
            if (r, g, b) not in pal:
                pal.append((r, g, b))
            px.append(pal.index((r, g, b)) + 1)
    frames.append(px)

def shift(rgb, dh):
    r, g, b = (v / 255 for v in rgb)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if s < 0.18 or l < 0.08 or l > 0.95:  # outline, whites: keep
        return rgb
    r, g, b = colorsys.hls_to_rgb((h + dh) % 1.0, l, s)
    return tuple(round(v * 255) for v in (r, g, b))

to565 = lambda c: ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)
out = ["/* Generated by tools/dragon.py from assets/creatures/deep-dragon.png: do not edit. */"]
for v, dh in enumerate(HUES):
    out.append(f"static const uint16_t DRG_PAL{v}[{len(pal) + 1}] = {{0,"
               + ",".join(f"0x{to565(shift(c, dh)):04x}u" for c in pal) + "};")
for name, px in zip(FRAMES, frames):
    out.append(f"static const uint8_t DRG_{name}_PX[{S * S}] = {{")
    for y in range(S):
        out.append("  " + ",".join(str(p) for p in px[y * S:(y + 1) * S]) + ",")
    out.append("};")
out.append("enum { " + ", ".join(f"DG_{n}" for n in FRAMES) + ", DG_COUNT };")
out.append("static const sprite_t DRAGON[DG_COUNT] = {"
           + ", ".join(f"{{{S}, {S}, DRG_{n}_PX, {{DRG_PAL0, DRG_PAL1, DRG_PAL2}}}}" for n in FRAMES) + "};")
(ROOT / "firmware/src/sprites_dragon.h").write_text("\n".join(out) + "\n")
print(f"sprites_dragon.h: {len(FRAMES)} frames, {len(pal)} colours")
