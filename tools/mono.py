#!/usr/bin/env python3
"""Art: every assets/art/NAME.png with its NAME.json (cell size, frame names) becomes frames in firmware/src/art.h.
Two inks: a pixel near cyan or white is the main ink, a pixel near pink is the accent; black is empty. Each ink is
one bit a pixel, rows packed MSB first.   python3 tools/mono.py [--preview OUT.png]"""
import json, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art"
INK, ACCENT = (122, 245, 234), (242, 134, 233)


def ink_of(rgb):
    r, g, b = rgb
    if max(rgb) < 100:
        return 0
    if r > 180 and g < 170 and b > 150:       # pink
        return 2
    return 1                                  # cyan, white


def pack(cell, x0, x1, y0, y1, want):
    bpr = (x1 - x0 + 7) // 8
    data = []
    for y in range(y0, y1):
        for bx in range(bpr):
            byte = 0
            for b in range(8):
                x = x0 + bx * 8 + b
                if x < x1 and ink_of(cell.getpixel((x, y))) == want:
                    byte |= 0x80 >> b
            data.append(byte)
    return data


out = ["/* Generated by tools/mono.py from the PNG strips in assets/art: do not edit. 1 bit a pixel an ink. */"]
names, previews = [], []
for js in sorted(ART.glob("*.json")):
    meta = json.loads(js.read_text())
    im = Image.open(js.with_suffix(".png")).convert("RGB")
    cw, ch = meta["cell"]
    group = js.stem.replace("-", "_").upper()
    for k, fname in enumerate(meta["frames"]):
        cell = im.crop((k * cw, 0, (k + 1) * cw, ch))
        bb = cell.point(lambda v: 255 if v > 99 else 0).convert("L").point(lambda v: 255 if v else 0).getbbox()
        x0, y0, x1, y1 = bb if bb else (0, 0, 1, 1)
        if group != "ICONS":                  # creatures keep their floor: trim the sides and the top
            y1 = ch
        a = pack(cell, x0, x1, y0, y1, 1)
        b = pack(cell, x0, x1, y0, y1, 2)
        cname = f"{group}_{fname.upper()}"
        out.append(f"static const uint8_t ART_{cname}_A[{len(a)}] = {{{','.join(map(str, a))}}};")
        acc = "0"
        if any(b):
            out.append(f"static const uint8_t ART_{cname}_B[{len(b)}] = {{{','.join(map(str, b))}}};")
            acc = f"ART_{cname}_B"
        names.append((cname, x1 - x0, y1 - y0, acc))
        previews.append(cell.crop((x0, y0, x1, y1)))
out.append("enum { " + ", ".join(f"A_{n}" for n, *_ in names) + ", A_COUNT };")
out.append("static const art_t ART[A_COUNT] = {"
           + ", ".join(f"{{{w}, {h}, ART_{n}_A, {acc}}}" for n, w, h, acc in names) + "};")
(ROOT / "firmware/src/art.h").write_text("\n".join(out) + "\n")
print(f"art.h: {len(names)} frames")
if "--preview" in sys.argv:
    W = sum(p.width * 3 + 6 for p in previews); H = max(p.height for p in previews) * 3
    sheet = Image.new("RGB", (W, H), (0, 0, 0)); x = 0
    for p in previews:
        q = p.copy(); px = q.load()
        for yy in range(q.height):
            for xx in range(q.width):
                i = ink_of(px[xx, yy]); px[xx, yy] = INK if i == 1 else ACCENT if i == 2 else (0, 0, 0)
        sheet.paste(q.resize((q.width * 3, q.height * 3), Image.NEAREST), (x, H - q.height * 3))
        x += q.width * 3 + 6
    sheet.save(sys.argv[sys.argv.index("--preview") + 1])
