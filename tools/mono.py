#!/usr/bin/env python3
"""1-bit art: every assets/art/NAME.png (white = ink) with its NAME.json (cell size, frame names) becomes
frames in firmware/src/art.h, one bit a pixel, rows packed MSB first.   python3 tools/mono.py [--preview OUT.png]"""
import json, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art"
out = ["/* Generated by tools/mono.py from the PNG strips in assets/art: do not edit. 1 bit a pixel, rows MSB first. */"]
names, previews = [], []
for js in sorted(ART.glob("*.json")):
    meta = json.loads(js.read_text())
    png = js.with_suffix(".png")
    im = Image.open(png).convert("L")
    cw, ch = meta["cell"]
    group = js.stem.replace("-", "_").upper()
    for k, fname in enumerate(meta["frames"]):
        cell = im.crop((k * cw, 0, (k + 1) * cw, ch))
        bb = cell.point(lambda v: 255 if v > 127 else 0).getbbox()
        x0, y0, x1, y1 = bb if bb else (0, 0, 1, 1)
        if group not in ("ICONS",):                 # creatures: keep the cell's floor, trim the sides and top
            y1 = ch
        w, h = x1 - x0, y1 - y0
        bpr = (w + 7) // 8
        data = []
        for y in range(y0, y1):
            for bx in range(bpr):
                byte = 0
                for b in range(8):
                    x = x0 + bx * 8 + b
                    if x < x1 and cell.getpixel((x, y)) > 127:
                        byte |= 0x80 >> b
                data.append(byte)
        cname = f"{group}_{fname.upper()}"
        out.append(f"static const uint8_t ART_{cname}_BITS[{len(data)}] = {{{','.join(str(v) for v in data)}}};")
        names.append((cname, w, h))
        previews.append(cell.crop((x0, y0, x1, y1)))
out.append("enum { " + ", ".join(f"A_{n}" for n, _, _ in names) + ", A_COUNT };")
out.append("static const art_t ART[A_COUNT] = {" + ", ".join(f"{{{w}, {h}, ART_{n}_BITS}}" for n, w, h in names) + "};")
(ROOT / "firmware/src/art.h").write_text("\n".join(out) + "\n")
print(f"art.h: {len(names)} frames, {sum(len(l) for l in out) // 5} B of source")
if "--preview" in sys.argv:
    W = sum(p.width * 3 + 6 for p in previews); H = max(p.height for p in previews) * 3
    sheet = Image.new("RGB", (W, H), (10, 13, 9)); x = 0
    for p in previews:
        sheet.paste(Image.new("RGB", (p.width * 3, p.height * 3), (214, 234, 160)), (x, H - p.height * 3),
                    p.resize((p.width * 3, p.height * 3), Image.NEAREST).point(lambda v: 255 if v > 127 else 0))
        x += p.width * 3 + 6
    sheet.save(sys.argv[sys.argv.index("--preview") + 1])
